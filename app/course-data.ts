export type LessonStatus = "未开始" | "进行中" | "已完成";

export type ExamplePart = {
  label: string;
  text: string;
};

export type Lesson = {
  id: string;
  title: string;
  goal: string;
  template: string;
  question: string;
  exampleParts: ExamplePart[];
  status: LessonStatus;
  readScore?: number;
  freeScore?: number;
  /** 编辑器中“示例”的原始文本（label：内容 分行），仅编辑器使用 */
  exampleText?: string;
};

export type Course = {
  id: string;
  title: string;
  lessons: Lesson[];
  expanded: boolean;
  /** 自由练习模块：只有“我的稿件”，没有课程标题/学习目标/核心结构/题目 */
  kind?: "free";
};

export function makeLesson(
  day: string,
  title: string,
  goal: string,
  template: string,
  question: string,
  parts: [string, string][],
  status: LessonStatus = "未开始",
): Lesson {
  return {
    id: `${day.toLowerCase().replace(/\s+/g, "-")}-${title.replace(/\s+/g, "-")}`,
    title: `${day} · ${title}`,
    goal,
    template,
    question,
    exampleParts: parts.map(([label, text]) => ({ label, text })),
    status,
  };
}

